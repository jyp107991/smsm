#!/usr/bin/env bash
# Regenerates everything derived from the migrations:
#   supabase/schema.sql             a snapshot of the public schema (for reading; never applied)
#   src/data/database.types.ts      TypeScript types (never written by hand)
# Usage: PGHOST=... PGUSER=... [PGPASSWORD=...] scripts/db-generate.sh [--check]
#   --check  regenerate into a temp dir and fail if the committed files differ (CI).
set -euo pipefail
cd "$(dirname "$0")/.."
DB=smsm_gen_$$
psql -q -d postgres -c "create database $DB"
trap 'psql -q -d postgres -c "drop database $DB" >/dev/null' EXIT
psql -q -d "$DB" -v ON_ERROR_STOP=1 -f tests/sql/auth_stub.sql
for f in supabase/migrations/*.sql; do psql -q -d "$DB" -v ON_ERROR_STOP=1 -f "$f" 2>&1 | { grep -v NOTICE || true; }; done

# Use the PostgreSQL 16 client when installed (newer pg_dump versions add version-specific lines).
PG_DUMP=pg_dump; [ -x /usr/lib/postgresql/16/bin/pg_dump ] && PG_DUMP=/usr/lib/postgresql/16/bin/pg_dump
OUT=$(mktemp -d)
{
  echo "-- GENERATED by scripts/db-generate.sh from supabase/migrations/. Do not edit; never applied."
  echo "-- To change the database, add a migration. This file is a readable snapshot of the public schema."
  "$PG_DUMP" -d "$DB" --schema-only --schema=public --no-owner \
    | grep -v -E '^(-- Dumped (from|by)|\\(un)?restrict |SET |SELECT pg_catalog.set_config)' \
    | grep -v -E 'ALTER COLUMN .* SET \(pg_attver=' \
    | cat -s
} > "$OUT/schema.sql"

HOST=${PGHOST:-127.0.0.1}; case "$HOST" in /*) HOST=127.0.0.1;; esac
URL="postgresql://${PGUSER:-postgres}:${PGPASSWORD:-postgres}@${HOST}:${PGPORT:-5432}/$DB"
npx --no-install supabase gen types --remote="$URL" --schema public > "$OUT/database.types.ts" 2>/dev/null

if [ "${1:-}" = "--check" ]; then
  ok=1
  diff -q "$OUT/schema.sql" supabase/schema.sql >/dev/null || { echo "supabase/schema.sql is stale: run npm run db:generate"; diff "$OUT/schema.sql" supabase/schema.sql | head -40; ok=0; }
  diff -q "$OUT/database.types.ts" src/data/database.types.ts >/dev/null || { echo "src/data/database.types.ts is stale: run npm run db:generate"; ok=0; }
  [ $ok = 1 ] && echo "generated files up to date"
  [ $ok = 1 ]
else
  cp "$OUT/schema.sql" supabase/schema.sql
  cp "$OUT/database.types.ts" src/data/database.types.ts
  echo "wrote supabase/schema.sql and src/data/database.types.ts"
fi
