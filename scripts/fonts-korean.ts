/**
 * Writes src/styles/fonts-korean-{a,b,c}.css: the Korean @font-face rules for each type option (DESIGN §3.2).
 * Usage: npx tsx scripts/fonts-korean.ts   (run again after changing a font package or the faces below)
 *
 * Fontsource splits each Korean font into about ninety small files, each covering a range of
 * characters (the package's unicode.json). Every range becomes one @font-face with that unicode-range,
 * so a phone downloads only the few files holding the Hangul it actually shows (a name, a shop), and
 * nothing at all for English-only screens. Only the numbered Korean slices are written: Latin is
 * declared by hand in type.css (preloaded and metric-matched), and latin-ext and Vietnamese are left
 * out. woff2 only; every browser smsm supports reads it.
 */
import { readFileSync, writeFileSync } from 'node:fs';

interface Face {
  /** The type option the face belongs to (the file it is written to). */
  option: 'a' | 'b' | 'c';
  /** The family name type.css uses. */
  family: string;
  /** Package folder in node_modules. */
  pkg: string;
  /** File-name stem in the package's files/ folder. */
  stem: string;
  /** Static weights to write; empty for a variable font. */
  weights: readonly number[];
  /** A variable font's weight range ("100 900"). */
  variable?: string;
}

const FACES: readonly Face[] = [
  { option: 'a', family: 'Gowun Batang', pkg: '@fontsource/gowun-batang', stem: 'gowun-batang', weights: [400] }, // 700 sets only the balance amount: no Hangul
  { option: 'a', family: 'Gowun Dodum', pkg: '@fontsource/gowun-dodum', stem: 'gowun-dodum', weights: [400] },
  { option: 'b', family: 'Hahmlet Variable', pkg: '@fontsource-variable/hahmlet', stem: 'hahmlet', weights: [], variable: '100 900' },
  { option: 'c', family: 'Nanum Myeongjo', pkg: '@fontsource/nanum-myeongjo', stem: 'nanum-myeongjo', weights: [400, 800] },
];

const header = (option: string) => [
  '/*',
  ' * Generated by scripts/fonts-korean.ts; do not edit by hand.',
  ` * Korean slices for type option ${option.toUpperCase()}: each file is fetched only when a character in its`,
  ' * unicode-range is on screen. Never preloaded, and left out of the service worker precache',
  ' * (vite.config.ts caches them as they are used). Option C shares Gowun Dodum with A.',
  ' */',
];
const files = { a: header('a'), b: header('b'), c: header('c') };

for (const face of FACES) {
  const out = files[face.option];
  const ranges = JSON.parse(readFileSync(`node_modules/${face.pkg}/unicode.json`, 'utf8')) as Record<string, string>;
  const slices = Object.entries(ranges)
    .filter(([key]) => /^\[\d+\]$/.test(key))
    .map(([key, range]) => ({ n: key.slice(1, -1), range }));
  const variants = face.variable
    ? [{ weight: face.variable, file: 'wght-normal', format: 'woff2-variations' }]
    : face.weights.map((w) => ({ weight: String(w), file: `${String(w)}-normal`, format: 'woff2' }));
  for (const v of variants) {
    for (const s of slices) {
      out.push(
        `@font-face { font-family: '${face.family}'; font-style: normal; font-display: swap; font-weight: ${v.weight}; ` +
          `src: url('${face.pkg}/files/${face.stem}-${s.n}-${v.file}.woff2') format('${v.format}'); unicode-range: ${s.range}; }`,
      );
    }
  }
}

for (const [option, out] of Object.entries(files)) {
  writeFileSync(`src/styles/fonts-korean-${option}.css`, out.join('\n') + '\n');
  console.log(`wrote src/styles/fonts-korean-${option}.css (${String(out.length - 7)} faces)`);
}
